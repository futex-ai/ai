//! Image generation DTOs and generator trait.

use std::{fmt, sync::Arc};

use async_trait::async_trait;
use internal_error::{DefinedAt, InternalError};
use serde::{Deserialize, Serialize};
use thiserror::Error;

use crate::{ErrorCore, ErrorKind, ModelUsage};

/// Provider-agnostic image generation or edit request.
#[derive(Clone, Debug, Default, Deserialize, Eq, PartialEq, Serialize)]
pub struct ImageGenerationRequest {
    /// Text instruction used to generate or edit the image.
    pub prompt: String,
    /// Ordered input images; a non-empty list selects edit mode.
    #[serde(default)]
    pub input_images: Vec<ImageGenerationInputImage>,
    /// Best-effort output aspect.
    #[serde(default)]
    pub aspect: ImageGenerationAspect,
    /// Best-effort output quality.
    #[serde(default)]
    pub quality: ImageGenerationQuality,
}

/// Decoded image supplied as edit context.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct ImageGenerationInputImage {
    /// Encoded image file bytes.
    pub data: Vec<u8>,
    /// MIME media type describing the image bytes.
    pub mime_type: String,
}

/// Provider-agnostic image aspect preference.
#[derive(Clone, Copy, Debug, Default, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ImageGenerationAspect {
    /// Let the provider select the output aspect.
    #[default]
    Auto,
    /// Prefer a square output.
    Square,
    /// Prefer a landscape output.
    Landscape,
    /// Prefer a portrait output.
    Portrait,
}

/// Provider-agnostic image quality preference.
#[derive(Clone, Copy, Debug, Default, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ImageGenerationQuality {
    /// Let the provider select the output quality.
    #[default]
    Auto,
    /// Prefer the provider's low-quality mode.
    Low,
    /// Prefer the provider's medium-quality mode.
    Medium,
    /// Prefer the provider's high-quality mode.
    High,
}

/// One generated image with its encoded file bytes and media type.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct GeneratedImage {
    /// Encoded generated image file bytes.
    pub data: Vec<u8>,
    /// MIME media type describing the generated bytes.
    pub mime_type: String,
}

/// Normalized response from one image generation call.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct ImageGenerationResponse {
    /// Provider that generated the image.
    pub provider: String,
    /// Configured provider model identifier.
    pub model_id: String,
    /// Exactly one generated image.
    pub image: GeneratedImage,
    /// Provider-revised prompt when one was reported.
    pub revised_prompt: Option<String>,
    /// Provider-reported normalized token usage.
    pub usage: ModelUsage,
}

/// Errors returned by the image generation boundary.
#[derive(Error)]
pub enum ImageGenerationError {
    /// The client submitted a blank prompt.
    #[error("[ai_interface/image_generator] prompt must not be empty")]
    EmptyPrompt {
        /// Shared failure details, including the adapter identity.
        core: Box<ErrorCore>,
    },
    /// An input image used an unsupported MIME media type.
    #[error("[ai_interface/image_generator] unsupported media type `{content_type}`")]
    UnsupportedMediaType {
        /// Shared failure details, including the adapter identity.
        core: Box<ErrorCore>,
        /// Unsupported MIME media type.
        content_type: String,
    },
    /// The provider returned no final image.
    #[error("[ai_interface/image_generator] no image returned by `{provider}` model `{model_id}`", provider = core.provider, model_id = core.model_id)]
    NoImage {
        /// Shared failure details, including the adapter identity.
        core: Box<ErrorCore>,
    },
    /// A classified provider or adapter failure.
    #[error("[ai_interface/image_generator] {kind:?} for `{provider}` model `{model_id}`: {message}", kind = core.kind, provider = core.provider, model_id = core.model_id, message = core.message)]
    Failure {
        /// Shared failure details.
        core: Box<ErrorCore>,
    },
    /// A classified failure with tracked definition and caller locations.
    #[error("[ai_interface/image_generator] {kind:?} for `{provider}` model `{model_id}`: {message}", kind = core.kind, provider = core.provider, model_id = core.model_id, message = core.message)]
    Internal {
        /// Shared failure details, including the adapter identity.
        core: Box<ErrorCore>,
        /// Original source and its tracked locations.
        source: InternalError,
    },
}

impl fmt::Debug for ImageGenerationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("ImageGenerationError")
            .field("core", self.core())
            .finish()
    }
}

impl ImageGenerationError {
    /// Wraps an internal failure without losing its source or caller location.
    #[track_caller]
    pub fn internal(
        provider: impl Into<String>,
        model_id: impl Into<String>,
        source: impl std::error::Error + Send + Sync + 'static,
    ) -> Self {
        Self::with_source(
            ErrorCore::new(ErrorKind::Internal, provider, model_id, "internal error"),
            source,
        )
    }

    /// Retains a source and its tracked locations with an explicit failure category.
    #[track_caller]
    pub fn with_source(
        core: ErrorCore,
        source: impl std::error::Error + Send + Sync + 'static,
    ) -> Self {
        const DEFINED_AT: DefinedAt = DefinedAt::new(module_path!(), file!(), line!(), column!());
        Self::Internal {
            core: Box::new(core),
            source: InternalError::from_source(DEFINED_AT, source),
        }
    }
}

/// Result alias for image generation operations.
pub type ImageGenerationResult<T> = std::result::Result<T, ImageGenerationError>;

#[cfg_attr(
    any(test, doctest, feature = "test-support"),
    unimock::unimock(api = ImageGeneratorMock)
)]
#[async_trait]
/// Provider-agnostic image generation and editing boundary.
pub trait ImageGenerator: Send + Sync {
    /// Generates or edits exactly one image.
    async fn generate(
        &self,
        request: &ImageGenerationRequest,
    ) -> ImageGenerationResult<ImageGenerationResponse>;
}

/// Shared dynamic image generator alias.
pub type DynImageGenerator = Arc<dyn ImageGenerator>;
