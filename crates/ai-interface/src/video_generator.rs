//! Video generation DTOs and generator trait.

use std::{fmt, sync::Arc};

use async_trait::async_trait;
use internal_error::{DefinedAt, InternalError};
use serde::{Deserialize, Serialize};
use thiserror::Error;

use crate::{ErrorCore, ErrorKind, ModelUsage};

/// Provider-agnostic video generation request.
#[derive(Clone, Debug, Default, Deserialize, Eq, PartialEq, Serialize)]
pub struct VideoGenerationRequest {
    /// Text instruction used to generate the video.
    pub prompt: String,
    /// Optional image used as the video's first frame.
    #[serde(default)]
    pub input_image: Option<VideoGenerationInputImage>,
    /// Portable output aspect.
    #[serde(default)]
    pub aspect: VideoGenerationAspect,
    /// Portable output duration.
    #[serde(default)]
    pub duration: VideoGenerationDuration,
    /// Portable output resolution.
    #[serde(default)]
    pub resolution: VideoGenerationResolution,
}

/// Decoded image supplied as a first-frame constraint.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct VideoGenerationInputImage {
    /// Encoded image file bytes.
    pub data: Vec<u8>,
    /// MIME media type describing the image bytes.
    pub mime_type: String,
}

/// Portable video aspect preference.
#[derive(Clone, Copy, Debug, Default, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum VideoGenerationAspect {
    /// Generate a 16:9 video.
    #[default]
    Landscape,
    /// Generate a 9:16 video.
    Portrait,
}

/// Portable video duration.
#[derive(Clone, Copy, Debug, Default, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum VideoGenerationDuration {
    /// Generate a four-second video.
    #[default]
    Seconds4,
    /// Generate an eight-second video.
    Seconds8,
}

impl VideoGenerationDuration {
    /// Returns the represented duration in seconds.
    pub fn seconds(self) -> u8 {
        match self {
            Self::Seconds4 => 4,
            Self::Seconds8 => 8,
        }
    }
}

/// Portable video output resolution.
#[derive(Clone, Copy, Debug, Default, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum VideoGenerationResolution {
    /// Generate a 720p video.
    #[default]
    P720,
}

/// One generated video with encoded file bytes and metadata.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct GeneratedVideo {
    /// Encoded generated video file bytes.
    pub data: Vec<u8>,
    /// MIME media type describing the generated bytes.
    pub mime_type: String,
    /// Duration of the generated clip in seconds.
    pub duration_seconds: u8,
    /// Encoded frame width in pixels.
    pub width: u16,
    /// Encoded frame height in pixels.
    pub height: u16,
}

/// Normalized response from one video generation call.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize)]
pub struct VideoGenerationResponse {
    /// Provider that generated the video.
    pub provider: String,
    /// Configured provider model identifier.
    pub model_id: String,
    /// Exactly one generated video.
    pub video: GeneratedVideo,
    /// Provider-reported normalized usage.
    pub usage: ModelUsage,
}

/// Errors returned by the video generation boundary.
#[derive(Error)]
pub enum VideoGenerationError {
    /// The client submitted a blank prompt.
    #[error("[ai_interface/video_generator] prompt must not be empty")]
    EmptyPrompt {
        /// Shared failure details, including the adapter identity.
        core: Box<ErrorCore>,
    },
    /// An input image used an unsupported MIME media type.
    #[error("[ai_interface/video_generator] unsupported media type `{content_type}`")]
    UnsupportedMediaType {
        /// Shared failure details, including the adapter identity.
        core: Box<ErrorCore>,
        /// Unsupported MIME media type.
        content_type: String,
    },
    /// The provider returned no final video.
    #[error("[ai_interface/video_generator] no video returned by `{provider}` model `{model_id}`", provider = core.provider, model_id = core.model_id)]
    NoVideo {
        /// Shared failure details, including the adapter identity.
        core: Box<ErrorCore>,
    },
    /// A classified provider or adapter failure.
    #[error("[ai_interface/video_generator] {kind:?} for `{provider}` model `{model_id}`: {message}", kind = core.kind, provider = core.provider, model_id = core.model_id, message = core.message)]
    Failure {
        /// Shared failure details.
        core: Box<ErrorCore>,
    },
    /// A classified failure with tracked definition and caller locations.
    #[error("[ai_interface/video_generator] {kind:?} for `{provider}` model `{model_id}`: {message}", kind = core.kind, provider = core.provider, model_id = core.model_id, message = core.message)]
    Internal {
        /// Shared failure details, including the adapter identity.
        core: Box<ErrorCore>,
        /// Original source and its tracked locations.
        source: InternalError,
    },
}

impl fmt::Debug for VideoGenerationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("VideoGenerationError")
            .field("core", self.core())
            .finish()
    }
}

impl VideoGenerationError {
    /// Wraps an internal failure without losing its source or caller location.
    #[track_caller]
    pub fn internal(
        provider: impl Into<String>,
        model_id: impl Into<String>,
        source: impl std::error::Error + Send + Sync + 'static,
    ) -> Self {
        Self::with_source(
            ErrorCore::new(ErrorKind::Internal, provider, model_id, "internal error"),
            source,
        )
    }

    /// Retains a source and its tracked locations with an explicit failure category.
    #[track_caller]
    pub fn with_source(
        core: ErrorCore,
        source: impl std::error::Error + Send + Sync + 'static,
    ) -> Self {
        const DEFINED_AT: DefinedAt = DefinedAt::new(module_path!(), file!(), line!(), column!());
        Self::Internal {
            core: Box::new(core),
            source: InternalError::from_source(DEFINED_AT, source),
        }
    }
}

/// Result alias for video generation operations.
pub type VideoGenerationResult<T> = std::result::Result<T, VideoGenerationError>;

#[cfg_attr(
    any(test, doctest, feature = "test-support"),
    unimock::unimock(api = VideoGeneratorMock)
)]
#[async_trait]
/// Provider-agnostic video generation boundary.
pub trait VideoGenerator: Send + Sync {
    /// Generates and downloads exactly one video.
    async fn generate(
        &self,
        request: &VideoGenerationRequest,
    ) -> VideoGenerationResult<VideoGenerationResponse>;
}

/// Shared dynamic video generator alias.
pub type DynVideoGenerator = Arc<dyn VideoGenerator>;
